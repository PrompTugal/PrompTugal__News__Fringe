#!/usr/bin/env node
// The map's observed half (work/38, architect.1.fringe@PrompTugal.dinis): who actually writes which paths, from git.
// Reads every commit on this branch (subject "<agent>: ..." or its Agent: trailer), groups the paths each agent wrote,
// and lists the files with more than one writer. Writes the `observed` block of data/architecture.json and keeps the
// rest of that file (repositories, accounts, environments, lines, proposed owners) as written by hand.
//   node admin/tools/architecture.mjs            write data/architecture.json
//   node admin/tools/architecture.mjs --print    print the observed block only
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'data/architecture.json');
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 });

// An agent's name, normalised: "x (brought onto dev by the lead)" counts as x; the Agent: trailer wins over the subject.
export function agentOf(subject, body) {
  const t = /^Agent:\s*(\S+@\S+)/m.exec(body || '');
  if (t) return t[1].replace(/[.,;]$/, '');
  const s = /^([A-Za-z][\w.-]*@[\w.-]+?)(?:\s*\([^)]*\))?:\s/.exec(subject || '');
  return s ? s[1] : null;
}
// A path's group: two levels and a ** below them; status files and the board kept at their own level.
export function groupOf(p) {
  const s = p.split('/');
  if (s[0] === 'team' && s[2] === 'agents' && s[3]) return p;
  if (s[0] === 'team' && s[1]) return `team/${s[1]}/**`;
  if (s[0] === 'work' && s[1] === 'design') return 'work/design/**';
  if (s.length <= 2) return p;
  return `${s[0]}/${s[1]}/**`;
}

export function observe() {
  const raw = git('log', '--no-merges', '--format=%x1e%H%x1f%cI%x1f%s%x1f%b%x1f', '--name-only');
  const commits = [];
  for (const rec of raw.split('\x1e').slice(1)) {
    const [h, at, subject, body, files] = rec.split('\x1f');
    commits.push({ h: h.slice(0, 7), at, subject, agent: agentOf(subject, body), files: (files || '').split('\n').map(x => x.trim()).filter(Boolean) });
  }
  const byAgent = {}, byFile = {};
  for (const c of commits) {
    const a = c.agent || 'unnamed';
    const r = byAgent[a] ||= { commits: 0, first: c.at, last: c.at, groups: {} };
    r.commits++; if (c.at < r.first) r.first = c.at; if (c.at > r.last) r.last = c.at;
    for (const f of c.files) {
      const g = groupOf(f); r.groups[g] = (r.groups[g] || 0) + 1;
      (byFile[f] ||= {})[a] = ((byFile[f] || {})[a] || 0) + 1;
    }
  }
  const agents = Object.entries(byAgent).sort((x, y) => y[1].commits - x[1].commits).map(([agent, r]) => ({
    agent, commits: r.commits, first: r.first.replace(/\+00:00$/, 'Z'), last: r.last.replace(/\+00:00$/, 'Z'),
    writes: Object.entries(r.groups).sort((x, y) => y[1] - x[1]).map(([path, n]) => ({ path, n })),
  }));
  const shared = Object.entries(byFile).filter(([, w]) => Object.keys(w).length > 1)
    .map(([file, w]) => ({ file, writers: Object.keys(w).length, by: Object.entries(w).sort((x, y) => y[1] - x[1]).map(([a, n]) => `${a} (${n})`) }))
    .sort((x, y) => y.writers - x.writers || x.file.localeCompare(y.file));
  return {
    about: 'Generated by node admin/tools/architecture.mjs from git log on dev: every commit counted under its Agent: trailer (or its subject); paths grouped two levels deep. Evidence, not policy: abp/policies.json is the policy.',
    generated: new Date().toISOString().replace(/\.\d+Z$/, 'Z'),
    commits: commits.length,
    since: commits.length ? commits[commits.length - 1].at.replace(/\+00:00$/, 'Z') : null,
    head: commits[0] && commits[0].h,
    agents, shared,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const o = observe();
  if (process.argv.includes('--print')) { console.log(JSON.stringify(o, null, 2)); process.exit(0); }
  const doc = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : {};
  doc.observed = o;
  fs.writeFileSync(OUT, JSON.stringify(doc, null, 2) + '\n');
  console.log(`data/architecture.json: ${o.commits} commits, ${o.agents.length} writers, ${o.shared.length} files with more than one writer`);
}
